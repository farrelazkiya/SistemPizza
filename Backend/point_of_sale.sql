create table if not exists menu_recipes (
    id bigint generated by default as identity primary key,
    menu_item_id bigint not null references menu_items(id) on delete cascade,
    ingredient_id bigint not null references ingredients(id) on delete cascade,
    qty_per_menu numeric(12,2) not null check (qty_per_menu > 0),
    unique (menu_item_id, ingredient_id)
);

create table if not exists sales (
    id bigint generated by default as identity primary key,
    total_amount numeric(15,2) not null default 0,
    created_at timestamptz not null default now()
);

create table if not exists sale_items (
    id bigint generated by default as identity primary key,
    sale_id bigint not null references sales(id) on delete cascade,
    menu_item_id bigint references menu_items(id) on delete set null,
    menu_name_at_time varchar(150) not null,
    quantity integer not null check (quantity > 0),
    unit_price numeric(15,2) not null check (unit_price >= 0),
    subtotal numeric(15,2) generated always as (quantity * unit_price) stored
);

alter table menu_recipes disable row level security;
alter table sales disable row level security;
alter table sale_items disable row level security;

create or replace function public.create_sale(p_items jsonb)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
    v_sale_id bigint;
    v_total numeric(15,2);
    v_item record;
    v_recipe record;
    v_shortage record;
begin
    if p_items is null or jsonb_typeof(p_items) <> 'array' then
        raise exception 'Keranjang penjualan harus berupa daftar menu.';
    end if;
    if jsonb_array_length(p_items) = 0 then
        raise exception 'Keranjang penjualan tidak boleh kosong.';
    end if;

    if exists (
        select 1
        from jsonb_to_recordset(p_items) as item(menu_item_id bigint, quantity integer)
        where item.menu_item_id is null or item.quantity is null or item.quantity <= 0
    ) then
        raise exception 'Menu dan jumlah porsi harus valid.';
    end if;

    for v_item in
        select item.menu_item_id, item.quantity
        from jsonb_to_recordset(p_items) as item(menu_item_id bigint, quantity integer)
    loop
        if not exists (select 1 from menu_items where id = v_item.menu_item_id) then
            raise exception 'Menu dengan ID % tidak ditemukan.', v_item.menu_item_id;
        end if;
        if not exists (select 1 from menu_recipes where menu_item_id = v_item.menu_item_id) then
            raise exception 'Resep untuk menu ID % belum diatur.', v_item.menu_item_id;
        end if;
    end loop;

    perform ingredient.id
    from ingredients as ingredient
    join (
        select recipe.ingredient_id
        from jsonb_to_recordset(p_items) as item(menu_item_id bigint, quantity integer)
        join menu_recipes as recipe on recipe.menu_item_id = item.menu_item_id
        group by recipe.ingredient_id
    ) as required on required.ingredient_id = ingredient.id
    order by ingredient.id
    for update of ingredient;

    select ingredient.name,
           ingredient.stock_qty,
           sum(recipe.qty_per_menu * item.quantity) as required_qty
    into v_shortage
    from jsonb_to_recordset(p_items) as item(menu_item_id bigint, quantity integer)
    join menu_recipes as recipe on recipe.menu_item_id = item.menu_item_id
    join ingredients as ingredient on ingredient.id = recipe.ingredient_id
    group by ingredient.id, ingredient.name, ingredient.stock_qty
    having ingredient.stock_qty < sum(recipe.qty_per_menu * item.quantity)
    limit 1;

    if found then
        raise exception 'Stok bahan % tidak cukup (tersedia %, dibutuhkan %).',
            v_shortage.name, v_shortage.stock_qty, v_shortage.required_qty;
    end if;

    select coalesce(sum(menu.selling_price * item.quantity), 0)
    into v_total
    from jsonb_to_recordset(p_items) as item(menu_item_id bigint, quantity integer)
    join menu_items as menu on menu.id = item.menu_item_id;

    insert into sales (total_amount)
    values (v_total)
    returning id into v_sale_id;

    for v_item in
        select item.menu_item_id, item.quantity, menu.name, menu.selling_price
        from jsonb_to_recordset(p_items) as item(menu_item_id bigint, quantity integer)
        join menu_items as menu on menu.id = item.menu_item_id
    loop
        insert into sale_items (sale_id, menu_item_id, menu_name_at_time, quantity, unit_price)
        values (v_sale_id, v_item.menu_item_id, v_item.name, v_item.quantity, v_item.selling_price);

        for v_recipe in
            select recipe.ingredient_id,
                   recipe.qty_per_menu * v_item.quantity as used_qty,
                   ingredient.unit_price
            from menu_recipes as recipe
            join ingredients as ingredient on ingredient.id = recipe.ingredient_id
            where recipe.menu_item_id = v_item.menu_item_id
        loop
            insert into inventory_logs (
                ingredient_id, menu_item_id, type, qty, unit_price_at_time, notes
            )
            values (
                v_recipe.ingredient_id,
                v_item.menu_item_id,
                'OUT',
                v_recipe.used_qty,
                v_recipe.unit_price,
                'Penjualan #' || v_sale_id
            );
        end loop;
    end loop;

    update ingredients as ingredient
    set stock_qty = ingredient.stock_qty - required.required_qty
    from (
        select recipe.ingredient_id,
               sum(recipe.qty_per_menu * item.quantity) as required_qty
        from jsonb_to_recordset(p_items) as item(menu_item_id bigint, quantity integer)
        join menu_recipes as recipe on recipe.menu_item_id = item.menu_item_id
        group by recipe.ingredient_id
    ) as required
    where ingredient.id = required.ingredient_id;

    return v_sale_id;
end;
$$;

create or replace function public.record_inventory_movement(
    p_ingredient_id bigint,
    p_type text,
    p_qty numeric,
    p_supplier_id bigint default null,
    p_menu_item_id bigint default null
)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
    v_stock_qty numeric(12,2);
    v_unit_price numeric(15,2);
    v_log_id bigint;
begin
    if p_type not in ('IN', 'OUT') then
        raise exception 'Jenis mutasi stok tidak valid.';
    end if;
    if p_qty is null or p_qty <= 0 then
        raise exception 'Kuantitas harus lebih besar dari nol.';
    end if;
    if p_type = 'IN' and p_supplier_id is null then
        raise exception 'Supplier wajib dipilih untuk stok masuk.';
    end if;
    if p_type = 'OUT' and p_menu_item_id is null then
        raise exception 'Menu wajib dipilih untuk stok keluar.';
    end if;

    select ingredient.stock_qty, ingredient.unit_price
    into v_stock_qty, v_unit_price
    from ingredients as ingredient
    where ingredient.id = p_ingredient_id
    for update;

    if not found then
        raise exception 'Bahan baku dengan ID % tidak ditemukan.', p_ingredient_id;
    end if;
    if p_type = 'OUT' and v_stock_qty < p_qty then
        raise exception 'Stok tidak cukup (tersedia %, dibutuhkan %).', v_stock_qty, p_qty;
    end if;

    insert into inventory_logs (
        ingredient_id, supplier_id, menu_item_id, type, qty, unit_price_at_time
    )
    values (
        p_ingredient_id, p_supplier_id, p_menu_item_id, p_type, p_qty, v_unit_price
    )
    returning id into v_log_id;

    update ingredients
    set stock_qty = case
        when p_type = 'IN' then v_stock_qty + p_qty
        else v_stock_qty - p_qty
    end
    where id = p_ingredient_id;

    return v_log_id;
end;
$$;

grant execute on function public.create_sale(jsonb) to anon, authenticated;
grant execute on function public.record_inventory_movement(bigint, text, numeric, bigint, bigint) to anon, authenticated;
