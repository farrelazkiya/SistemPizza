create table if not exists public.inventory_batches (
    id bigint generated by default as identity primary key,
    ingredient_id bigint not null references public.ingredients(id),
    batch_number varchar(100) not null,
    expiry_date date,
    quantity_received numeric(12,2) not null check (quantity_received > 0),
    quantity_remaining numeric(12,2) not null
        check (quantity_remaining >= 0 and quantity_remaining <= quantity_received),
    unit_cost numeric(15,2) not null check (unit_cost >= 0),
    received_at timestamptz not null default now(),
    source_log_id bigint references public.inventory_logs(id)
);

create index if not exists inventory_batches_fifo_idx
    on public.inventory_batches (ingredient_id, expiry_date, received_at, id)
    where quantity_remaining > 0;
create index if not exists inventory_batches_expiry_idx
    on public.inventory_batches (expiry_date)
    where quantity_remaining > 0 and expiry_date is not null;

alter table public.inventory_logs
    add column if not exists batch_id bigint references public.inventory_batches(id),
    add column if not exists batch_number varchar(100),
    add column if not exists expiry_date date,
    add column if not exists unit_cost numeric(15,2);

create table if not exists public.inventory_batch_consumptions (
    id bigint generated by default as identity primary key,
    inventory_log_id bigint not null references public.inventory_logs(id) on delete cascade,
    batch_id bigint not null references public.inventory_batches(id),
    quantity numeric(12,2) not null check (quantity > 0),
    unit_cost numeric(15,2) not null check (unit_cost >= 0),
    created_at timestamptz not null default now()
);

create index if not exists inventory_batch_consumptions_log_idx
    on public.inventory_batch_consumptions (inventory_log_id);

insert into public.inventory_batches (
    ingredient_id, batch_number, quantity_received, quantity_remaining,
    unit_cost, received_at
)
select ingredient.id,
       'OPENING-' || ingredient.id::text,
       ingredient.stock_qty,
       ingredient.stock_qty,
       ingredient.unit_price,
       coalesce((
           select min(log.created_at)
           from public.inventory_logs as log
           where log.ingredient_id = ingredient.id and log.type = 'IN'
       ), now())
from public.ingredients as ingredient
where ingredient.stock_qty > 0
  and not exists (
      select 1 from public.inventory_batches as batch
      where batch.ingredient_id = ingredient.id
  );

alter table public.inventory_batches disable row level security;
alter table public.inventory_batch_consumptions disable row level security;
revoke all on public.inventory_batches, public.inventory_batch_consumptions from anon, authenticated;
grant select on public.inventory_batches to anon, authenticated;
grant select on public.inventory_batch_consumptions to anon, authenticated;

create or replace function public.apply_inventory_batch_tracking()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    v_batch_id bigint;
    v_batch record;
    v_remaining numeric(12,2);
    v_allocated numeric(12,2);
    v_total_cost numeric(20,4) := 0;
    v_single_batch_id bigint;
    v_batch_count integer := 0;
begin
    if new.type = 'IN' then
        insert into public.inventory_batches (
            ingredient_id, batch_number, expiry_date, quantity_received,
            quantity_remaining, unit_cost, received_at, source_log_id
        )
        values (
            new.ingredient_id,
            coalesce(nullif(trim(new.batch_number), ''), 'ADJ-' || new.id::text),
            new.expiry_date,
            new.qty,
            new.qty,
            coalesce(new.unit_cost, new.unit_price_at_time),
            new.created_at,
            new.id
        )
        returning id into v_batch_id;

        update public.inventory_logs
        set batch_id = v_batch_id,
            batch_number = coalesce(nullif(trim(new.batch_number), ''), 'ADJ-' || new.id::text),
            unit_cost = coalesce(new.unit_cost, new.unit_price_at_time)
        where id = new.id;
        return new;
    end if;

    v_remaining := new.qty;
    for v_batch in
        select batch.id, batch.quantity_remaining, batch.unit_cost
        from public.inventory_batches as batch
        where batch.ingredient_id = new.ingredient_id
          and batch.quantity_remaining > 0
        order by batch.expiry_date asc nulls last, batch.received_at, batch.id
        for update
    loop
        exit when v_remaining <= 0;
        v_allocated := least(v_remaining, v_batch.quantity_remaining);

        update public.inventory_batches
        set quantity_remaining = quantity_remaining - v_allocated
        where id = v_batch.id;

        insert into public.inventory_batch_consumptions (
            inventory_log_id, batch_id, quantity, unit_cost
        )
        values (new.id, v_batch.id, v_allocated, v_batch.unit_cost);

        v_remaining := v_remaining - v_allocated;
        v_total_cost := v_total_cost + (v_allocated * v_batch.unit_cost);
        v_batch_count := v_batch_count + 1;
        v_single_batch_id := v_batch.id;
    end loop;

    if v_remaining > 0 then
        raise exception 'Stok batch bahan ID % tidak cukup untuk mutasi (kurang %).',
            new.ingredient_id, v_remaining;
    end if;

    update public.inventory_logs
    set unit_price_at_time = round(v_total_cost / new.qty, 2),
        unit_cost = round(v_total_cost / new.qty, 2),
        batch_id = case when v_batch_count = 1 then v_single_batch_id else null end
    where id = new.id;

    return new;
end;
$$;

drop trigger if exists inventory_logs_apply_batch_tracking on public.inventory_logs;
create trigger inventory_logs_apply_batch_tracking
after insert on public.inventory_logs
for each row execute function public.apply_inventory_batch_tracking();

drop function if exists public.record_inventory_movement(bigint, text, numeric, bigint, bigint, text, text, text, date);
drop function if exists public.record_inventory_movement(bigint, text, numeric, bigint, bigint, text, text);

create function public.record_inventory_movement(
    p_ingredient_id bigint,
    p_type text,
    p_qty numeric,
    p_supplier_id bigint default null,
    p_menu_item_id bigint default null,
    p_payment_method text default null,
    p_reason text default null,
    p_batch_number text default null,
    p_expiry_date date default null
)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
    v_stock_qty numeric(12,2);
    v_unit_price numeric(15,2);
    v_purchase_unit_price numeric(15,2);
    v_log_id bigint;
begin
    if p_type is null or p_type not in ('IN', 'OUT') then
        raise exception 'Jenis mutasi stok tidak valid.';
    end if;
    if p_qty is null or p_qty <= 0 or p_qty <> round(p_qty, 2) then
        raise exception 'Kuantitas harus lebih besar dari nol dan maksimal dua angka desimal.';
    end if;

    if p_type = 'IN' then
        if p_supplier_id is null then
            raise exception 'Supplier wajib dipilih untuk stok masuk.';
        end if;
        if p_payment_method is null or p_payment_method not in ('CASH', 'CREDIT') then
            raise exception 'Metode pembayaran pembelian harus dipilih.';
        end if;
        if p_batch_number is null or length(trim(p_batch_number)) = 0
           or length(trim(p_batch_number)) > 100 then
            raise exception 'Nomor batch wajib diisi (maksimal 100 karakter).';
        end if;
        if p_expiry_date is null or p_expiry_date < current_date then
            raise exception 'Tanggal kedaluwarsa wajib diisi dan tidak boleh sudah lewat.';
        end if;

        select catalog.fixed_unit_price
        into v_purchase_unit_price
        from public.supplier_ingredients as catalog
        where catalog.ingredient_id = p_ingredient_id
          and catalog.supplier_id = p_supplier_id;
        if not found then
            raise exception 'Supplier tersebut tidak terdaftar untuk bahan baku ini.';
        end if;
    else
        if p_supplier_id is not null or p_menu_item_id is not null then
            raise exception 'Pengurangan manual hanya boleh dicatat sebagai barang basi atau kedaluwarsa.';
        end if;
        if p_reason is null or length(trim(p_reason)) = 0 or length(trim(p_reason)) > 300 then
            raise exception 'Alasan barang basi atau kedaluwarsa wajib diisi (maksimal 300 karakter).';
        end if;
    end if;

    select ingredient.stock_qty, ingredient.unit_price
    into v_stock_qty, v_unit_price
    from public.ingredients as ingredient
    where ingredient.id = p_ingredient_id
    for update;

    if not found then
        raise exception 'Bahan baku dengan ID % tidak ditemukan.', p_ingredient_id;
    end if;
    if p_type = 'OUT' and v_stock_qty < p_qty then
        raise exception 'Stok tidak cukup (tersedia %, dibutuhkan %).', v_stock_qty, p_qty;
    end if;

    insert into public.inventory_logs (
        ingredient_id, supplier_id, menu_item_id, type, qty, unit_price_at_time,
        payment_method, paid_at, notes, movement_reason,
        batch_number, expiry_date, unit_cost
    )
    values (
        p_ingredient_id,
        p_supplier_id,
        null,
        p_type,
        p_qty,
        case when p_type = 'IN' then v_purchase_unit_price else v_unit_price end,
        case when p_type = 'IN' then p_payment_method else null end,
        case when p_type = 'IN' and p_payment_method = 'CASH' then now() else null end,
        case when p_type = 'OUT' then trim(p_reason) else null end,
        case when p_type = 'OUT' then 'SPOILED' else null end,
        case when p_type = 'IN' then trim(p_batch_number) else null end,
        case when p_type = 'IN' then p_expiry_date else null end,
        case when p_type = 'IN' then v_purchase_unit_price else v_unit_price end
    )
    returning id into v_log_id;

    update public.ingredients
    set stock_qty = case when p_type = 'IN' then v_stock_qty + p_qty else v_stock_qty - p_qty end,
        unit_price = case
            when p_type = 'IN' then round(
                ((v_stock_qty * v_unit_price) + (p_qty * v_purchase_unit_price))
                / (v_stock_qty + p_qty),
                2
            )
            else v_unit_price
        end
    where id = p_ingredient_id;

    return v_log_id;
end;
$$;

grant execute on function public.record_inventory_movement(
    bigint, text, numeric, bigint, bigint, text, text, text, date
) to anon, authenticated;

