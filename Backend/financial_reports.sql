alter table inventory_logs
    add column if not exists payment_method text
        check (payment_method in ('CASH', 'CREDIT')),
    add column if not exists paid_at timestamptz;

create table if not exists operating_expenses (
    id bigint generated by default as identity primary key,
    description varchar(200) not null,
    category varchar(100) not null,
    amount numeric(15,2) not null check (amount > 0),
    payment_method text not null check (payment_method in ('CASH', 'CREDIT')),
    created_at timestamptz not null default now(),
    paid_at timestamptz
);

alter table operating_expenses disable row level security;
grant select, insert, update on operating_expenses to anon, authenticated;
grant usage, select on sequence operating_expenses_id_seq to anon, authenticated;

create index if not exists inventory_logs_paid_at_idx
    on inventory_logs (paid_at) where paid_at is not null;
create index if not exists operating_expenses_created_at_idx
    on operating_expenses (created_at);
create index if not exists operating_expenses_paid_at_idx
    on operating_expenses (paid_at) where paid_at is not null;

drop function if exists public.record_inventory_movement(bigint, text, numeric, bigint, bigint);
drop function if exists public.record_inventory_movement(bigint, text, numeric, bigint, bigint, text);

create or replace function public.record_inventory_movement(
    p_ingredient_id bigint,
    p_type text,
    p_qty numeric,
    p_supplier_id bigint default null,
    p_menu_item_id bigint default null,
    p_payment_method text default null,
    p_unit_price numeric default null
)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
    v_stock_qty numeric(12,2);
    v_unit_price numeric(15,2);
    v_log_id bigint;
begin
    if p_type is null or p_type not in ('IN', 'OUT') then
        raise exception 'Jenis mutasi stok tidak valid.';
    end if;
    if p_qty is null or p_qty <= 0 then
        raise exception 'Kuantitas harus lebih besar dari nol.';
    end if;
    if p_type = 'IN' and p_supplier_id is null then
        raise exception 'Supplier wajib dipilih untuk stok masuk.';
    end if;
    if p_type = 'IN' and (p_payment_method is null or p_payment_method not in ('CASH', 'CREDIT')) then
        raise exception 'Metode pembayaran pembelian harus dipilih.';
    end if;
    if p_type = 'IN' and (p_unit_price is null or p_unit_price < 0) then
        raise exception 'Harga beli per satuan harus valid.';
    end if;
    if p_type = 'OUT' and p_menu_item_id is null then
        raise exception 'Menu wajib dipilih untuk stok keluar.';
    end if;

    select ingredient.stock_qty, ingredient.unit_price
    into v_stock_qty, v_unit_price
    from ingredients as ingredient
    where ingredient.id = p_ingredient_id
    for update;

    if not found then
        raise exception 'Bahan baku dengan ID % tidak ditemukan.', p_ingredient_id;
    end if;
    if p_type = 'OUT' and v_stock_qty < p_qty then
        raise exception 'Stok tidak cukup (tersedia %, dibutuhkan %).', v_stock_qty, p_qty;
    end if;

    insert into inventory_logs (
        ingredient_id, supplier_id, menu_item_id, type, qty, unit_price_at_time,
        payment_method, paid_at
    )
    values (
        p_ingredient_id, p_supplier_id, p_menu_item_id, p_type, p_qty,
        case when p_type = 'IN' then p_unit_price else v_unit_price end,
        case when p_type = 'IN' then p_payment_method else null end,
        case when p_type = 'IN' and p_payment_method = 'CASH' then now() else null end
    )
    returning id into v_log_id;

    update ingredients
    set stock_qty = case when p_type = 'IN' then v_stock_qty + p_qty else v_stock_qty - p_qty end,
        unit_price = case
            when p_type = 'IN' then round(((v_stock_qty * v_unit_price) + (p_qty * p_unit_price)) / (v_stock_qty + p_qty), 2)
            else v_unit_price
        end
    where id = p_ingredient_id;

    return v_log_id;
end;
$$;

create or replace function public.create_operating_expense(
    p_description text,
    p_category text,
    p_amount numeric,
    p_payment_method text
)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
    v_expense_id bigint;
begin
    if p_description is null or length(trim(p_description)) = 0 then
        raise exception 'Keterangan biaya wajib diisi.';
    end if;
    if p_category is null or length(trim(p_category)) = 0 then
        raise exception 'Kategori biaya wajib diisi.';
    end if;
    if p_amount is null or p_amount <= 0 then
        raise exception 'Nominal biaya harus lebih besar dari nol.';
    end if;
    if p_payment_method is null or p_payment_method not in ('CASH', 'CREDIT') then
        raise exception 'Metode pembayaran biaya tidak valid.';
    end if;

    insert into operating_expenses (
        description, category, amount, payment_method, paid_at
    )
    values (
        trim(p_description),
        trim(p_category),
        p_amount,
        p_payment_method,
        case when p_payment_method = 'CASH' then now() else null end
    )
    returning id into v_expense_id;

    return v_expense_id;
end;
$$;

create or replace function public.settle_financial_payable(
    p_source_type text,
    p_source_id bigint
)
returns void
language plpgsql
security invoker
set search_path = public
as $$
declare
    v_updated_id bigint;
begin
    if p_source_type = 'PURCHASE' then
        update inventory_logs
        set paid_at = now()
        where id = p_source_id
          and type = 'IN'
          and payment_method = 'CREDIT'
          and paid_at is null
        returning id into v_updated_id;
    elsif p_source_type = 'EXPENSE' then
        update operating_expenses
        set paid_at = now()
        where id = p_source_id
          and payment_method = 'CREDIT'
          and paid_at is null
        returning id into v_updated_id;
    else
        raise exception 'Jenis utang tidak valid.';
    end if;

    if v_updated_id is null then
        raise exception 'Utang tidak ditemukan atau sudah dibayar.';
    end if;
end;
$$;

grant execute on function public.record_inventory_movement(bigint, text, numeric, bigint, bigint, text, numeric)
    to anon, authenticated;
grant execute on function public.create_operating_expense(text, text, numeric, text)
    to anon, authenticated;
grant execute on function public.settle_financial_payable(text, bigint)
    to anon, authenticated;
